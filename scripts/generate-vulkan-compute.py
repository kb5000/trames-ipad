#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-or-later
"""Generate paired host/guest compute metadata and promotion mappings."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
schema = json.loads((root / 'runtime/crates/trames-vulkan/compute-profile.json').read_text())
header = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Generated by scripts/generate-vulkan-compute.py; edit compute-profile.json.']
rs, c = header.copy(), header.copy()
api = lambda n: f'vk::API_VERSION_1_{n - 10}' if n else 'vk::API_VERSION_1_0'
capi = lambda n: (f'VK_API_VERSION_1_{n - 10}' if n < 14 else f'VK_MAKE_API_VERSION(0, 1, {n - 10}, 0)') if n else 'UINT32_MAX'
rs += ['pub(super) const EXTENSIONS: &[(u64, &std::ffi::CStr, u32)] = &[']
for e in schema['extensions']:
    rs += [f'    (1 << {e["index"]}, c"{e["extension"]}", {api(e["minimum_api"])}),']
rs += ['];']
for e in schema['extensions']:
    if e['name'] in ('storage_class', 'maintenance3', 'memory_budget', 'host_image_copy', 'format_feature_flags2', 'sample_locations', 'line_rasterization'):
        rs += [f'pub(super) const EXT_{e["name"].upper()}: u64 = 1 << {e["index"]};']
rs += ['compute_features! {']
bit_mask = 0
for f in schema['features']:
    fields = ', '.join(str(f['bit'] + i) + ' => ' + x['rust'] + ' : ' + ('true' if x.get('expose', True) else 'false') for i, x in enumerate(f['fields']))
    promoted = schema['extensions'][f['extension']]['promoted']
    rs += [f'    {f["name"]}: {f["type"]}, {f["extension"]}, {promoted} => [{fields}];']
    for i, field in enumerate(f['fields']):
        assert not bit_mask & (1 << (f['bit'] + i))
        bit_mask |= 1 << (f['bit'] + i)
rs += ['}']
constants = {'extended_dynamic_state3_sample_locations_enable','extended_dynamic_state3_line_rasterization_mode','extended_dynamic_state','extended_dynamic_state2','extended_dynamic_state2_patch_control_points','extended_dynamic_state3_depth_clamp_enable','extended_dynamic_state3_polygon_mode','host_image_copy','dynamic_rendering','pipeline_creation_cache_control','sampler_ycbcr_conversion', 'buffer_device_address', 'subgroup_size_control', 'compute_full_subgroups', 'shader_shared_float32_atomic_add', 'shader_shared_float32_atomics', 'host_query_reset','multiview','separate_depth_stencil_layouts','descriptor_binding_uniform_buffer_update_after_bind','descriptor_binding_sampled_image_update_after_bind','descriptor_binding_storage_image_update_after_bind','descriptor_binding_storage_buffer_update_after_bind','descriptor_binding_uniform_texel_buffer_update_after_bind','descriptor_binding_storage_texel_buffer_update_after_bind','descriptor_binding_update_unused_while_pending','descriptor_binding_partially_bound','descriptor_binding_variable_descriptor_count'}
for f in schema['features']:
    for i, field in enumerate(f['fields']):
        if field['rust'] in constants:
            rs += [f'pub(super) const {field["rust"].upper()}: u128 = 1 << {f["bit"] + i};']
for f in schema['core12']:
    assert not bit_mask & (1 << f['bit'])
    bit_mask |= 1 << f['bit']
    rs += [f'pub(super) const {f["rust"].upper()}: u128 = 1 << {f["bit"]};']
rs += ['impl Selected {', '    pub fn core12_features(&mut self, features: u128, legacy: u64) {']
for f in schema['features']:
    if schema['extensions'][f['extension']]['promoted'] == 12:
        for field in f['fields']:
            rs += [f'        self.vulkan12.{field["rust"]} = self.{f["name"]}.{field["rust"]};']
for f in schema['core12']:
    rs += [f'        self.vulkan12.{f["rust"]} = u32::from(features & (1 << {f["bit"]}) != 0);']
for field, bit in [('scalar_block_layout', 11), ('imageless_framebuffer', 9), ('timeline_semaphore', 1)]:
    rs += [f'        self.vulkan12.{field} = u32::from(legacy & (1 << {bit}) != 0);']
rs += ['    }', '}', 'fn query_core12(caps: &mut Capabilities, query: &ash::khr::get_physical_device_properties2::Instance, physical: vk::PhysicalDevice) {', '    if caps.api < vk::API_VERSION_1_2 { return; }', '    let mut native = vk::PhysicalDeviceVulkan12Features::default();', '    let mut features = vk::PhysicalDeviceFeatures2::default().push_next(&mut native);', '    unsafe { query.get_physical_device_features2(physical, &mut features); }']
for f in schema['core12']:
    rs += [f'    if native.{f["rust"]} != 0 {{ caps.features |= {f["rust"].upper()}; }}']
rs += ['}']
rs += ['compute_properties! {']
for q in schema['properties']:
    fields = ', '.join(x['rust'] + ('.as_raw() as u32' if x['kind'] == 'ShaderFloatControlsIndependence' else '.as_raw()' if x['kind'] not in ('u32', 'Bool32') else '') for x in q['fields'])
    ext = '0' if q['extension'] is None else '1u64 << ' + str(q['extension'])
    rs += [f'    {q["type"]}, {ext} => [{fields}];']
rs += ['}', '// c_char is signed on Apple and unsigned on AArch64 Linux.', '#[allow(clippy::unnecessary_cast)]', 'fn query_aggregate_properties(caps: &mut Capabilities, query: &ash::khr::get_physical_device_properties2::Instance, physical: vk::PhysicalDevice) {']
for q in schema['aggregate_properties']:
    ty = q['type']; first = q['fields'][0]['rust']
    rs += [f'    if caps.api >= {api(q["minimum_api"])} {{', f'        let mut native = vk::{ty}::default();', '        let mut properties = vk::PhysicalDeviceProperties2::default().push_next(&mut native);', '        unsafe { query.get_physical_device_properties2(physical, &mut properties); }']
    if ty == 'PhysicalDeviceVulkan11Properties':
        rs += ['        native.subgroup_supported_stages &= vk::ShaderStageFlags::VERTEX | vk::ShaderStageFlags::FRAGMENT | vk::ShaderStageFlags::COMPUTE;']
    rs += [f'        let start = std::mem::offset_of!(vk::{ty}, {first});', f'        let mut bytes = vec![0; std::mem::size_of::<vk::{ty}>() - start];']
    for f in q['fields']:
        field = f['rust']; kind = f['kind']
        if kind == 'ConformanceVersion':
            continue  # The bridge never inherits the native conformance certificate.
        if kind.startswith('['):
            value = f'native.{field}.to_vec()' if kind.startswith('[u8;') else f'native.{field}.iter().map(|&v| v as u8).collect::<Vec<_>>()'
        elif kind in ('u32', 'Bool32', 'u64', 'DeviceSize'):
            value = f'native.{field}.to_le_bytes()'
        else:
            value = f'native.{field}.as_raw().to_le_bytes()'
        rs += [f'        let at = std::mem::offset_of!(vk::{ty}, {field}) - start;', f'        let value = {value};', '        bytes[at..at + value.len()].copy_from_slice(&value);']
    rs += ['        caps.aggregate_properties.insert(native.s_type.as_raw() as u32, bytes);', '    }']
rs += ['}']
c += ['static const struct compute_extension compute_extensions[] = {']
for e in schema['extensions']:
    c += [f'    {{"{e["extension"]}", 1UL << {e["index"]}}},']
c += ['};', 'static const struct compute_feature compute_features[] = {']
for f in schema['features']:
    promoted = schema['extensions'][f['extension']]['promoted']
    c += [f'    {{VK_STRUCTURE_TYPE_{f["structure_type"]}, offsetof(Vk{f["type"]}, {f["fields"][0]["c"]}), {len(f["fields"])}, {f["bit"]}, 1UL << {f["extension"]}, {capi(promoted)}}},']
c += ['};', 'static const struct compute_core12 compute_core12[] = {']
for f in schema['core12']:
    ext = '0' if f['extension'] is None else '1UL << ' + str(f['extension'])
    c += [f'    {{{f["bit"]}, {ext}}},']
c += ['};', 'static const struct compute_aggregate compute_aggregates[] = {']
for q in schema['aggregates']:
    arrays = ['{' + ', '.join(str(f[key]) for f in q['fields']) + '}' for key in ('bit', 'legacy', 'capability')]
    c += [f'    {{VK_STRUCTURE_TYPE_{q["structure_type"]}, offsetof(Vk{q["type"]}, {q["fields"][0]["c"]}), {len(q["fields"])}, {q["seen_mask"]}UL, {", ".join(arrays)}}},']
c += ['};', 'static const struct compute_property compute_properties[] = {']
for q in schema['properties']:
    ext = '0' if q['extension'] is None else '1UL << ' + str(q['extension'])
    c += [f'    {{VK_STRUCTURE_TYPE_{q["structure_type"]}, offsetof(Vk{q["type"]}, {q["fields"][0]["c"]}), {len(q["fields"]) * 4}, {ext}, VK_API_VERSION_1_1}},']
c += ['    {VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_MAINTENANCE_3_PROPERTIES, offsetof(VkPhysicalDeviceMaintenance3Properties, maxPerSetDescriptors), 16, 1UL << 16, VK_API_VERSION_1_1},']
for q in schema['aggregate_properties']:
    ty = q['type']; first = q['fields'][0]['c']
    c += [f'    {{VK_STRUCTURE_TYPE_{q["structure_type"]}, offsetof(Vk{ty}, {first}), sizeof(Vk{ty}) - offsetof(Vk{ty}, {first}), 0, {capi(q["minimum_api"])}}},']
c += ['};']
outputs = {root / 'runtime/crates/trames-vulkan/src/backend/compute_schema.rs': '\n'.join(rs) + '\n', root / 'accelerator/vulkan/compute-schema.inc': '\n'.join(c) + '\n'}
for path, content in outputs.items():
    if a.check:
        assert path.read_text() == content, 'refresh compute metadata: ' + str(path)
    else:
        path.write_text(content)
print('paired compute metadata verified' if a.check else 'paired compute metadata generated')
